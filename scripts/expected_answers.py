"""Expected answers for the README's sample queries, from the data rather than memory
(PLAN.md §11). Writes docs/samples/expected.md: for each sample, the opposing team, which
attacking types pay off against it, and what's catchable before the battle, with the query or
tool each fact comes from. No model calls.

    uv run python scripts/expected_answers.py
"""

import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from agent import pipeline  # noqa: E402
from agent.context import RequestContext  # noqa: E402
from agent.examples import EXAMPLES  # noqa: E402
from agent.session import SESSIONS  # noqa: E402
from agent.state import RunState  # noqa: E402
from agent.tools.battles import team  # noqa: E402
from agent.tools.common import effectiveness  # noqa: E402
from agent.tools.encounters import catchable  # noqa: E402
from agent.tools.outlook import TYPES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "samples" / "expected.md"
TARGET = {"tate-liza": "gym7_tate_liza", "nuzlocke-juan": "gym8_juan", "randomizer-tate-liza": "gym7_tate_liza"}
TEAM_SQL = ("SELECT s.name, m.level, m.held_item FROM trainer_mons m JOIN species s USING (species_id) "
            "WHERE m.trainer_const = '{const}' ORDER BY m.slot")


def context_for(ex: dict) -> RequestContext:
    session_id = f"expected-{ex['id']}"
    SESSIONS.clear(session_id)
    session = SESSIONS.get(session_id)
    if ex.get("sample_log"):
        pipeline.load_log((ROOT / "static" / "samples" / ex["sample_log"]).read_text(encoding="utf-8"), ex["sample_log"], session_id)
    pipeline.apply_form_state(session, RunState(**ex["run_state"]))
    return RequestContext(state=session.state, con=session.con, randomizer=session.randomizer)


def section(ex: dict) -> str:
    ctx = context_for(ex)
    b = ctx.prog.get(TARGET[ex["id"]])
    mons, _ = team(ctx, b)
    lines = [f"## {ex['title']} (`{ex['id']}`)", "", f"**Question:** {ex['message']}", ""]
    if ctx.randomizer:
        lines += [f"Randomized: the sample log `{ex['sample_log']}` replaces this battle's team (`trainer_mons` is a session view over the log).", ""]
    lines += [f"**{b.label}** ({b.battle_format} battle), from `{TEAM_SQL.format(const=mons[0]['trainer_const'])}`:", ""]
    lines += [f"- {m['species']} Lv{m['level']} ({'/'.join(m['types'])})" + (f", holding {m['held_item']}" if m["held_item"] else "") for m in mons]
    scores = sorted(((sum(effectiveness(t, m["types"]) >= 2 for m in mons), -sum(effectiveness(t, m["types"]) < 1 for m in mons), t)
                     for t in TYPES), reverse=True)
    best = [t for hits, _, t in scores if hits >= max(2, scores[0][0] - 1)][:4]
    lines += ["", "**Attacking types that hit most of the team super-effectively** (Gen III type chart, `type_efficacy`): "
              + ", ".join(f"{t} ({hits}/{len(mons)})" for hits, _, t in scores if t in best), ""]
    found = catchable(ctx, b.id, types=best)
    rules = ctx.state.ruleset.describe()
    lines += [f"**Catchable before {b.label}** with those types (`get_catchable`: encounter tables, HM and story gates"
              + ("; the player's rules applied" if rules else "") + f"): {found['species_count']} species. The most available:", ""]
    for sp in found["species"][:8]:
        place = sp["places"][0]
        odds = f"{place['rate_pct']}%" if "rate_pct" in place else f"{place['count']} one-off encounter(s)"
        lines.append(f"- {sp['species']} ({'/'.join(sp['types'])}): {place['where']}, {place['method']}, Lv{place['lv'][0]}-{place['lv'][1]}, {odds}")
    if found.get("excluded_by_rules"):
        lines += ["", f"Excluded by the rules: {len(found['excluded_by_rules'])} species (" + "; ".join(rules) + ")."]
    lines += ["", f"**A good answer** names picks from this list (or explains a stronger long-term choice that's also on it), "
              f"says where and when to catch them, and accounts for the {b.battle_format} format"
              + (", the level cap and the used areas" if ctx.state.ruleset.nuzlocke else "")
              + (", and uses the log's team, not the vanilla one" if ctx.randomizer else "") + ".", ""]
    return "\n".join(lines)


def main() -> int:
    body = ["# Expected answers for the README samples", "",
            "Generated by `scripts/expected_answers.py` from `data/emerald.duckdb` and the agent's code tools; no model involved.", ""]
    body += [section(ex) for ex in EXAMPLES if ex.get("readme")]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
